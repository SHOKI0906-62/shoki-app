// 経穴コード → 要穴の説明の配列（例：['原穴', '五兪穴の兪土穴', '八会穴（脈会）']）
export function specialOf(code, nameOf) {
  const name = nameOf(code);
  const meridian = code.replace(/\d+$/, '');
  const out = [];
  for (const [k, list] of Object.entries(G)) {
    if (k in LABEL) continue;
    if (list.split(',').includes(name)) out.push(k);
  }
  const list = GOYU[meridian]?.split(',') || [];
  const i = list.indexOf(name);
  if (i >= 0) out.push(`${KIND[i]}${(YIN.includes(meridian) ? GYO_YIN : GYO_YANG)[i]}穴`);
  for (const [k, map] of Object.entries(LABEL)) {
    if (map[name]) out.push(`${k}（${map[name]}）`);
  }
  // 郄穴・絡穴・原穴は、その経穴が属する経絡のものだけ（名前の重複がないので名前だけで判定）
  return out;
}
